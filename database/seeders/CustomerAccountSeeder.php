<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Models\Account;
use App\Models\AccountProduct;
use App\Models\Customer;
use App\Models\GeneralLedger;
use App\Models\User;
use App\Services\Account\AccountService;
use App\Services\AccountProduct\AccountProductService;
use App\Services\Customer\CustomerService;
use App\Services\Posting\PostingService;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Auth;

// One individual customer with a funded savings account — useful test data for exercising
// the customer/account/posting flow without clicking through the admin UI every time.
class CustomerAccountSeeder extends Seeder
{
    private const CIF_NUMBER = 'CIF-SEED-0001';
    private const FUNDING_AMOUNT = '3000000';

    public function run(): void
    {
        $this->call(AccountProductSeeder::class);

        $maker   = User::where('username', 'admin1')->firstOrFail();
        $checker = User::where('username', 'admin2')->firstOrFail();

        Auth::guard('user')->setUser($maker);

        $customer = $this->seedCustomer();
        $account  = $this->seedAccount($customer);

        $this->fundAccount($account, $maker, $checker);
    }

    private function seedCustomer(): Customer
    {
        $existing = Customer::where('cif_number', self::CIF_NUMBER)->first();
        if ($existing) {
            return $existing;
        }

        $customer = app(CustomerService::class)->create([
            'customer_type' => 'individual',
            'first_name'    => 'Tunde',
            'last_name'     => 'John',
            'email'         => 'tunde.john@example.com',
            'phone'         => '08012345678',
            'gender'        => 'male',
            'dob'           => '1990-01-01',
        ]);

        // cif_number is auto-generated by CustomerService::create() — pin it to a known
        // value so this seeder is idempotent across runs.
        $customer->update(['cif_number' => self::CIF_NUMBER, 'status' => 'active']);

        return $customer->refresh();
    }

    private function seedAccount(Customer $customer): Account
    {
        $existing = Account::where('customer_id', $customer->id)->first();
        if ($existing) {
            return $existing;
        }

        $savingsProduct = AccountProduct::where('product_type', 'savings')->firstOrFail();

        if ($savingsProduct->status !== 'active') {
            $savingsProduct = app(AccountProductService::class)->approve($savingsProduct);
        }

        return app(AccountService::class)->openAccountForCustomer($customer, [
            'account_product_id' => $savingsProduct->id,
            'account_type'       => 'savings',
        ]);
    }

    // Mirrors a real teller cash deposit: debit Cash in Vault, credit the customer's
    // account, through the real posting engine (maker + a different checker), not a raw
    // balance edit. Cash in Vault is topped up first if it has no funds of its own yet —
    // there's no "opening balance" mechanism in the app, so this is the one place a
    // direct balance set is legitimate (a one-time capitalization entry, not a fabricated
    // customer transaction).
    private function fundAccount(Account $account, User $maker, User $checker): void
    {
        if ((float) $account->account_balance >= (float) self::FUNDING_AMOUNT) {
            return;
        }

        $cashInVault = GeneralLedger::where('name', 'cash_in_vault')->firstOrFail();

        if ((float) $cashInVault->balance < (float) self::FUNDING_AMOUNT) {
            $cashInVault->update(['balance' => self::FUNDING_AMOUNT]);
        }

        Auth::guard('user')->setUser($maker);

        $posting = app(PostingService::class)->create([
            'source_type'      => 'general_ledger',
            'source_id'        => $cashInVault->id,
            'destination_type' => 'account',
            'destination_id'   => $account->id,
            'amount'           => self::FUNDING_AMOUNT,
            'module'           => 'postings',
            'transaction_type' => 'cash_deposit',
            'channel'          => 'branch',
            'remarks'          => "Seed funding for account '{$account->account_number}'.",
        ]);

        Auth::guard('user')->setUser($checker);

        app(PostingService::class)->approve($posting);
    }
}
